import LoremSwiftum
import SwiftParser
import SwiftSyntax

/// Generates derived Swift source for declarations annotated with Previewable macros.
public enum PreviewableSourceGenerator {

  /// Generates the doubles, fake factories, and preview accessors declared by the supplied source files.
  /// - Parameter sources: The complete Swift source texts to parse together.
  /// - Returns: A compilable Swift source file containing the generated declarations.
  /// - Throws: When an annotated declaration uses an unsupported form or requirement.
  public static func generate(from sources: [String]) throws -> String {
    var imports: Set<String> = []
    var doubles: [String] = []
    var fakes: [String] = []
    var unavailableFakes: [String] = []
    var previewConfigurations: [String] = []
    var fakeDefaultValues = FakeDefaultValues()
    let files = sources.map { Parser.parse(source: $0) }
    let enumDefaults = enumDefaults(in: files)

    for file in files {
      let sourceImports = file.statements.compactMap {
        $0.item.as(ImportDeclSyntax.self)?.path.trimmedDescription
      }

      for statement in file.statements {
        if let declaration = statement.item.as(ProtocolDeclSyntax.self),
           attribute(named: "PreviewableDouble", in: declaration.attributes) != nil {
          imports.formUnion(sourceImports)
          let generated = try generateDouble(
            from: declaration,
            enumDefaults: enumDefaults,
            fakeDefaultValues: &fakeDefaultValues
          )
          doubles.append(generated.declaration)
          previewConfigurations.append(generated.previewConfiguration)
          continue
        }

        if let declaration = statement.item.as(StructDeclSyntax.self),
           attribute(named: "PreviewableFake", in: declaration.attributes) != nil {
          imports.formUnion(sourceImports)
          fakes.append(
            try generateFake(
              from: declaration,
              enumDefaults: enumDefaults,
              fakeDefaultValues: &fakeDefaultValues
            )
          )
          unavailableFakes.append(try generateUnavailableFake(from: declaration))
          continue
        }

        if let declaration = statement.item.as(ClassDeclSyntax.self),
           attribute(named: "PreviewableFake", in: declaration.attributes) != nil {
          imports.formUnion(sourceImports)
          fakes.append(
            try generateFake(
              from: declaration,
              enumDefaults: enumDefaults,
              fakeDefaultValues: &fakeDefaultValues
            )
          )
          unavailableFakes.append(try generateUnavailableFake(from: declaration))
        }
      }
    }

    imports.remove("Mercury")
    let importSource = imports.sorted().map { "import \($0)" }.joined(separator: "\n")
    let doubleDeclarations = doubles.joined(separator: "\n\n")
    let fakeDeclarations = fakes.joined(separator: "\n\n")
    let unavailableFakeDeclarations = unavailableFakes.joined(separator: "\n\n")
    let previewDeclarations = previewConfigurations.joined(separator: "\n\n")
    return """
      //
      // Copyright © 2026 and confidential to Roland Lariotte. All rights reserved.
      //

      // Generated by Mercury PreviewableBuildToolPlugin. Do not edit.

      \(importSource)

      #if DEBUG
      \(doubleDeclarations)
      \(fakeDeclarations)
      #else
      \(unavailableFakeDeclarations)
      #endif

      \(previewDeclarations)
      """
  }
}

private extension PreviewableSourceGenerator {

  struct GeneratedDouble {
    let declaration: String
    let previewConfiguration: String
  }

  struct GeneratedProperty {
    let stub: String
    let requirement: String
  }

  struct GeneratedMethod {
    let stubs: [String]
    let requirement: String
  }

  struct FakeDefaultValues {
    var strings: Set<String> = []
    var numbers: Set<Int> = []
    var urls: Set<Int> = []
    var uuids: Set<Int> = []
  }

  struct StoredProperty {
    let name: String
    let type: String
    let isMutable: Bool
  }

  enum DefaultContext {
    case double
    case fake
  }

  static func attribute(
    named name: String,
    in attributes: AttributeListSyntax
  ) -> AttributeSyntax? {
    for element in attributes {
      guard case .attribute(let attribute) = element,
            attribute.attributeName.trimmedDescription == name
      else { continue }
      return attribute
    }
    return nil
  }

  static func enumDefaults(in files: [SourceFileSyntax]) -> [String: String] {
    var defaults: [String: String] = [:]
    for file in files {
      for statement in file.statements {
        guard let declaration = statement.item.as(EnumDeclSyntax.self) else {
          continue
        }
        for member in declaration.memberBlock.members {
          guard let caseDeclaration = member.decl.as(EnumCaseDeclSyntax.self),
                let element = caseDeclaration.elements.first
          else { continue }
          if element.parameterClause == nil {
            defaults[declaration.name.text] =
              "\(declaration.name.text).\(element.name.text)"
          }
          break
        }
      }
    }
    return defaults
  }

  static func generateDouble(
    from declaration: ProtocolDeclSyntax,
    enumDefaults: [String: String],
    fakeDefaultValues: inout FakeDefaultValues
  ) throws -> GeneratedDouble {
    guard declaration.primaryAssociatedTypeClause == nil,
          declaration.genericWhereClause == nil
    else {
      throw GenerationError.message(
        "@PreviewableDouble does not support protocols with associated types or generic constraints"
      )
    }

    let protocolName = declaration.name.text
    let dependencyName = protocolName.hasSuffix("Protocol")
      ? String(protocolName.dropLast("Protocol".count))
      : protocolName
    let doubleName = dependencyName + "Double"
    let access = accessPrefix(from: declaration.modifiers)
    var stubDeclarations: [String] = []
    var requirementDeclarations: [String] = []
    var methodNames: Set<String> = []

    for member in declaration.memberBlock.members {
      if let variable = member.decl.as(VariableDeclSyntax.self) {
        for property in try propertyDeclarations(
            from: variable,
            access: access,
            enumDefaults: enumDefaults,
            fakeDefaultValues: &fakeDefaultValues
        ) {
          stubDeclarations.append(property.stub)
          requirementDeclarations.append(property.requirement)
        }
        continue
      }
      if let function = member.decl.as(FunctionDeclSyntax.self) {
        guard methodNames.insert(function.name.text).inserted else {
          throw GenerationError.message(
            "@PreviewableDouble does not support overloaded requirement '\(function.name.text)'"
          )
        }
        let method = try methodDeclaration(
            from: function,
            access: access,
            enumDefaults: enumDefaults,
            fakeDefaultValues: &fakeDefaultValues
          )
        stubDeclarations.append(contentsOf: method.stubs)
        requirementDeclarations.append(method.requirement)
        continue
      }
      if member.decl.is(AssociatedTypeDeclSyntax.self)
        || member.decl.is(SubscriptDeclSyntax.self) {
        throw GenerationError.message(
          "@PreviewableDouble does not support associated types or subscripts"
        )
      }
    }

    var sections: [String] = []
    if !stubDeclarations.isEmpty {
      sections.append(
        (["// Mock values"] + stubDeclarations).joined(separator: "\n")
      )
    }
    sections.append(
      [
        "// Preview value",
        "/// The shared double for SwiftUI preview dependency injection.",
        "///",
        "/// Instantiated once as a dummy, but can act as a mock or spy",
        "/// depending on the configured stubs and tracked calls when used.",
        "/// - Important: Use this value only from SwiftUI previews.",
        "\(access)nonisolated static let preview = MainActor.assumeIsolated { \(doubleName)() }"
      ].joined(separator: "\n")
    )
    sections.append("\(access)nonisolated init() {}")
    sections.append(
      [
        "// Spy values",
        "/// The protocol method names invoked on this double.",
        "\(access)private(set) var calledMethods: [String] = []",
        "/// The arguments captured for each invoked protocol method.",
        "\(access)private(set) var passedParameters: [String: [Any?]] = [:]"
      ].joined(separator: "\n")
    )
    if !requirementDeclarations.isEmpty {
      sections.append(
        (["// Protocol requirements"] + requirementDeclarations)
          .joined(separator: "\n")
      )
    }

    let body = sections.map { indent($0, by: 2) }.joined(separator: "\n\n")
    let generatedDeclaration = """
      /// A test double for `\(protocolName)`.
      ///
      /// Configure stubs and inspect recorded calls when testing protocol consumers.
      /// - Important: Use this value only in Debug builds.
      \(access)final class \(doubleName): \(protocolName) {

      \(body)
      }
      """
    let doubleAccessorName = doubleName.lowercasingFirstCharacter
    let previewConfiguration = """
      /// The shared `\(doubleName)` for SwiftUI preview dependency injection.
      /// - Important: Use this value only from SwiftUI previews.
      @inline(__always)
      \(access)nonisolated var \(doubleAccessorName): any \(protocolName) {
      #if DEBUG
        \(doubleName).preview
      #else
        preconditionFailure("\(doubleAccessorName) is unavailable outside Debug builds and SwiftUI previews")
      #endif
      }
      """
    return GeneratedDouble(
      declaration: generatedDeclaration,
      previewConfiguration: previewConfiguration
    )
  }

  static func propertyDeclarations(
    from declaration: VariableDeclSyntax,
    access: String,
    enumDefaults: [String: String],
    fakeDefaultValues: inout FakeDefaultValues
  ) throws -> [GeneratedProperty] {
    guard !isStatic(declaration.modifiers) else {
      throw GenerationError.message(
        "@PreviewableDouble does not support static property requirements"
      )
    }

    return try declaration.bindings.map { binding in
      guard let identifier = binding.pattern.as(IdentifierPatternSyntax.self),
            let type = binding.typeAnnotation?.type.trimmedDescription,
            let accessorBlock = binding.accessorBlock
      else {
        throw GenerationError.message(
          "@PreviewableDouble requires named, explicitly typed protocol properties"
        )
      }

      let name = identifier.identifier.text
      let isSettable = accessorBlock.trimmedDescription.contains("set")
      let defaultValue = automaticDefault(
        for: type,
        context: .double,
        enumDefaults: enumDefaults,
        fakeDefaultValues: &fakeDefaultValues
      )
      let stub = "\(access)var \(name)Stub: \(type) = \(defaultValue)"
      if isSettable {
        return GeneratedProperty(
          stub: stub,
          requirement: """
            \(access)var \(name): \(type) {
              get { \(name)Stub }
              set { \(name)Stub = newValue }
            }
            """
        )
      }
      return GeneratedProperty(
        stub: stub,
        requirement: "\(access)var \(name): \(type) { \(name)Stub }"
      )
    }
  }

  static func methodDeclaration(
    from function: FunctionDeclSyntax,
    access: String,
    enumDefaults: [String: String],
    fakeDefaultValues: inout FakeDefaultValues
  ) throws -> GeneratedMethod {
    guard !isStatic(function.modifiers),
          function.genericParameterClause == nil,
          function.genericWhereClause == nil
    else {
      throw GenerationError.message(
        "@PreviewableDouble does not support static or generic method requirements"
      )
    }

    let methodName = function.name.text
    var declarations: [String] = []
    var parameters: [String] = []
    for parameter in function.signature.parameterClause.parameters {
      guard parameter.ellipsis == nil else {
        throw GenerationError.message(
          "@PreviewableDouble does not support variadic parameters"
        )
      }
      let localName = parameter.secondName?.text ?? parameter.firstName.text
      guard localName != "_" else {
        throw GenerationError.message(
          "@PreviewableDouble requires a named local parameter"
        )
      }
      parameters.append(localName)
    }

    let effects = function.signature.effectSpecifiers?.trimmedDescription ?? String()
    let isThrowing = effects.contains("throws")
    if isThrowing {
      declarations.append("\(access)var \(methodName)ErrorStub: (any Error)?")
    }

    let returnType = function.signature.returnClause?.type.trimmedDescription
    let returnsValue = returnType != nil && returnType != "Void" && returnType != "()"
    if let returnType, returnsValue {
      let defaultValue = automaticDefault(
        for: returnType,
        context: .double,
        enumDefaults: enumDefaults,
        fakeDefaultValues: &fakeDefaultValues
      )
      declarations.append("\(access)var \(methodName)Stub: \(returnType) = \(defaultValue)")
    }

    var body = [
      "calledMethods.append(#function)",
      "passedParameters[#function] = [\(parameters.joined(separator: ", "))]"
    ]
    if isThrowing {
      body.append("if let \(methodName)ErrorStub { throw \(methodName)ErrorStub }")
    }
    if returnsValue {
      body.append("return \(methodName)Stub")
    }
    let methodBody = body.map { "  \($0)" }.joined(separator: "\n")
    let signature = functionSignature(from: function)
    let requirement = """
      \(access)func \(methodName)\(signature) {
      \(methodBody)
      }
      """
    return GeneratedMethod(stubs: declarations, requirement: requirement)
  }

  static func generateFake(
    from declaration: some DeclGroupSyntax,
    enumDefaults: [String: String],
    fakeDefaultValues: inout FakeDefaultValues
  ) throws -> String {
    let typeName: String
    let members: MemberBlockItemListSyntax
    let access: String
    let isClass: Bool

    if let structure = declaration.as(StructDeclSyntax.self) {
      typeName = structure.name.text
      members = structure.memberBlock.members
      access = accessPrefix(from: structure.modifiers)
      isClass = false
    } else if let classDeclaration = declaration.as(ClassDeclSyntax.self) {
      typeName = classDeclaration.name.text
      members = classDeclaration.memberBlock.members
      access = accessPrefix(from: classDeclaration.modifiers)
      isClass = true
    } else {
      throw GenerationError.message(
        "@PreviewableFake can only be applied to a structure or class"
      )
    }

    let properties = try eligibleStoredProperties(in: members)
    if isClass && properties.contains(where: { !$0.isMutable }) {
      throw GenerationError.message(
        "@PreviewableFake classes require mutable fake properties and an accessible init()"
      )
    }

    var parameterDeclarations: [String] = []
    for property in properties {
      let defaultValue = automaticDefault(
        for: property.type,
        context: .fake,
        enumDefaults: enumDefaults,
        fakeDefaultValues: &fakeDefaultValues
      )
      parameterDeclarations.append(
        "\(property.name): \(property.type) = \(defaultValue)"
      )
    }
    let parameters = parameterDeclarations.joined(separator: ",\n")
    let values = properties.enumerated().map { index, property in
      let comma = index == properties.count - 1 ? String() : ","
      return "  \(property.name): \(property.name)\(comma)"
    }
    let body = ([".init("] + values + [")"]).joined(separator: "\n")

    let method = """
      /// Returns a fake `\(typeName)` with generated defaults or caller-provided stored-property values.
      \(access)static func fake(
      \(indent(parameters, by: 2))
      ) -> \(typeName) {
      \(indent(body, by: 2))
      }
      """
    var extensionMembers: [String] = []
    if isClass && !properties.isEmpty {
      let initializerParameters = properties.map {
        "\($0.name): \($0.type)"
      }.joined(separator: ",\n")
      let assignments = properties.map {
        "self.\($0.name) = \($0.name)"
      }.joined(separator: "\n")
      extensionMembers.append(
        """
        \(access)convenience init(
        \(indent(initializerParameters, by: 2))
        ) {
          self.init()
        \(indent(assignments, by: 2))
        }
        """
      )
    }
    extensionMembers.append(method)
    let extensionBody = extensionMembers.map {
      indent($0, by: 2)
    }.joined(separator: "\n\n")
    return """
      /// Provides a fake factory for Debug builds, test targets, and SwiftUI previews.
      extension \(typeName) {
      \(extensionBody)
      }
      """
  }

  static func generateUnavailableFake(
    from declaration: some DeclGroupSyntax
  ) throws -> String {
    let typeName: String
    let members: MemberBlockItemListSyntax
    let access: String

    if let structure = declaration.as(StructDeclSyntax.self) {
      typeName = structure.name.text
      members = structure.memberBlock.members
      access = accessPrefix(from: structure.modifiers)
    } else if let classDeclaration = declaration.as(ClassDeclSyntax.self) {
      typeName = classDeclaration.name.text
      members = classDeclaration.memberBlock.members
      access = accessPrefix(from: classDeclaration.modifiers)
    } else {
      throw GenerationError.message(
        "@PreviewableFake can only be applied to a structure or class"
      )
    }

    let properties = try eligibleStoredProperties(in: members)
    let message = String(
      reflecting: "\(typeName).fake(...) is unavailable outside Debug builds and SwiftUI previews"
    )
    let parameters = properties.map {
      "\($0.name): \($0.type) = { () -> \($0.type) in preconditionFailure(\(message)) }()"
    }.joined(separator: ",\n")
    return """
      /// Preserves the `fake(...)` signature outside Debug builds.
      extension \(typeName) {
        /// Prevents fake construction outside Debug builds.
        /// - Warning: Available only in Debug builds.
        @inline(__always)
        \(access)static func fake(
      \(indent(parameters, by: 4))
        ) -> \(typeName) {
          preconditionFailure(\(message))
        }
      }
      """
  }

  static func eligibleStoredProperties(
    in members: MemberBlockItemListSyntax
  ) throws -> [StoredProperty] {
    var properties: [StoredProperty] = []
    for member in members {
      guard let variable = member.decl.as(VariableDeclSyntax.self),
            !isStatic(variable.modifiers)
      else { continue }

      for binding in variable.bindings {
        guard binding.accessorBlock == nil,
              let identifier = binding.pattern.as(IdentifierPatternSyntax.self)
        else { continue }

        let isMutable = variable.bindingSpecifier.tokenKind == .keyword(.var)
        let hasInitializer = binding.initializer != nil
        guard isMutable || !hasInitializer else { continue }
        guard let type = inferredType(from: binding) else {
          throw GenerationError.message(
            "@PreviewableFake requires an explicit or inferable type for '\(identifier.identifier.text)'"
          )
        }
        properties.append(
          StoredProperty(
            name: identifier.identifier.text,
            type: type,
            isMutable: isMutable
          )
        )
      }
    }
    return properties
  }

  static func inferredType(
    from binding: PatternBindingSyntax
  ) -> String? {
    if let type = binding.typeAnnotation?.type.trimmedDescription {
      return type
    }
    if let initializer = binding.initializer?.value {
      if let call = initializer.as(FunctionCallExprSyntax.self),
         let reference = call.calledExpression.as(DeclReferenceExprSyntax.self) {
        return reference.baseName.text
      }
      if initializer.is(StringLiteralExprSyntax.self) { return "String" }
      if initializer.is(BooleanLiteralExprSyntax.self) { return "Bool" }
      if initializer.is(FloatLiteralExprSyntax.self) { return "Double" }
      if initializer.is(IntegerLiteralExprSyntax.self) { return "Int" }
    }
    return nil
  }

  static func accessPrefix(from modifiers: DeclModifierListSyntax) -> String {
    let accessLevels = ["open", "public", "package"]
    guard let modifier = modifiers.first(where: { accessLevels.contains($0.name.text) }) else {
      return String()
    }
    return "\(modifier.name.text) "
  }

  static func isStatic(_ modifiers: DeclModifierListSyntax) -> Bool {
    modifiers.contains { ["class", "static"].contains($0.name.text) }
  }

  static func automaticDefault(
    for type: String,
    context: DefaultContext,
    enumDefaults: [String: String],
    fakeDefaultValues: inout FakeDefaultValues
  ) -> String {
    let compactType = type.filter { !$0.isWhitespace }
    if compactType.hasSuffix("?") { return ".none" }
    if compactType == "Bool" { return "false" }
    if compactType == "String" || compactType == "Substring" {
      return context == .fake
        ? nextLoremString(used: &fakeDefaultValues.strings)
        : ".init()"
    }
    if numericTypes.contains(compactType) {
      return context == .fake ? nextNonZeroNumber(used: &fakeDefaultValues.numbers) : ".zero"
    }
    if compactType.hasPrefix("[") && compactType.hasSuffix("]") {
      return compactType.contains(":") ? "[:]" : "[]"
    }
    if compactType.hasPrefix("Array<") || compactType.hasPrefix("Set<") { return "[]" }
    if compactType.hasPrefix("Dictionary<") { return "[:]" }
    if compactType == "Image" { return "Image(systemName: \"photo\")" }
    if compactType == "Date" { return ".now" }
    if compactType == "UUID" {
      return context == .fake ? nextFakeUUID(used: &fakeDefaultValues.uuids) : "UUID()"
    }
    if compactType == "URL" {
      if context == .fake { return nextFakeURL(used: &fakeDefaultValues.urls) }
      return "URL(string: \"https://example.com\")!"
    }
    if let enumDefault = enumDefaults[compactType] { return enumDefault }
    return ".init()"
  }

  static func nextLoremString(used strings: inout Set<String>) -> String {
    for _ in 0..<100 {
      let wordCount = 2 + strings.count % 3
      let string = Lorem.words(wordCount)
      if strings.insert(string).inserted {
        return String(reflecting: string)
      }
    }
    let string = "\(Lorem.words(2)) \(strings.count + 1)"
    strings.insert(string)
    return String(reflecting: string)
  }

  static func nextNonZeroNumber(used numbers: inout Set<Int>) -> String {
    let number = (numbers.max() ?? 0) + 1
    numbers.insert(number)
    return String(number)
  }

  static func nextFakeURL(used urls: inout Set<Int>) -> String {
    let number = (urls.max() ?? 0) + 1
    urls.insert(number)
    return "URL(string: \"https://fake.url.com/\(number)\")!"
  }

  static func nextFakeUUID(used uuids: inout Set<Int>) -> String {
    let number = (uuids.max() ?? 0) + 1
    uuids.insert(number)
    let suffix = String(repeating: "0", count: max(0, 12 - String(number).count)) + String(number)
    return "UUID(uuidString: \"00000000-0000-0000-0000-\(suffix)\")!"
  }

  static func indent(_ source: String, by spaces: Int) -> String {
    let prefix = String(repeating: " ", count: spaces)
    return source.split(separator: "\n", omittingEmptySubsequences: false)
      .map { $0.isEmpty ? String() : prefix + $0 }
      .joined(separator: "\n")
  }

  static let numericTypes: Set<String> = [
    "Double", "Float", "Float16", "Float32", "Float64", "Float80",
    "Int", "Int8", "Int16", "Int32", "Int64",
    "UInt", "UInt8", "UInt16", "UInt32", "UInt64"
  ]

  static func functionSignature(from function: FunctionDeclSyntax) -> String {
    let parameters = function.signature.parameterClause.parameters.map { parameter in
      var parameter = parameter
      parameter.trailingComma = nil
      return parameter.trimmedDescription
    }
    let parameterClause: String
    if parameters.isEmpty {
      parameterClause = "()"
    } else if parameters.count == 1 {
      parameterClause = "(\(parameters[0]))"
    } else {
      parameterClause = "(\n  \(parameters.joined(separator: ",\n  "))\n)"
    }

    let effects = function.signature.effectSpecifiers.map {
      " \($0.trimmedDescription)"
    } ?? String()
    let returnClause = function.signature.returnClause.map {
      " \($0.trimmedDescription)"
    } ?? String()
    return parameterClause + effects + returnClause
  }
}

private extension String {

  var lowercasingFirstCharacter: String {
    guard let first else { return self }
    return first.lowercased() + dropFirst()
  }
}

private enum GenerationError: Error, CustomStringConvertible {
  case message(String)

  var description: String {
    switch self {
    case .message(let message): message
    }
  }
}
